# EDA-1: размеры, пересечение train/корпус, доля «той же локации», категории, фильтры бенчмарка.
# Запуск из корня репозитория: python experiments/01_eda/eda1.py (нужны data/ из scripts/prep.py … split.py)
import pandas as pd, numpy as np
pd.set_option('display.width', 250); pd.set_option('display.max_columns', 30); pd.set_option('display.max_colwidth', 80)
tr = pd.read_parquet('train.parquet', columns=['search_query','search_location_id','search_is_delivery_search','search_infm_params_text','search_category','item_id','item_title_raw','item_category_id','item_microcat_id','item_location_id','item_infm_params_text'])
bq = pd.read_parquet('benchmark_queries.parquet')
bi = pd.read_parquet('benchmark_items.parquet', columns=['item_id','item_title_raw','item_category_id','item_microcat_id','item_location_id','item_infm_params_text'])
print(tr.head(10))
print(bq.head(10))
print('train uniq queries', tr.search_query.nunique(), 'uniq items', tr.item_id.nunique())
print('train uniq (q,loc)', tr.groupby(['search_query','search_location_id']).ngroups)
qkey = ['search_query','search_location_id','search_is_delivery_search','search_infm_params_text','search_category']
g = tr.groupby(qkey, dropna=False).size()
print('train uniq full query key', len(g), 'rows/key dist', g.describe())
print('bench uniq query texts', bq.search_query.nunique(), 'of', len(bq))
print('bench full-key dups', bq.duplicated(qkey).sum())
print('bench query text in train', bq.search_query.isin(set(tr.search_query)).mean())
print('bench (q,loc) in train', bq.set_index(['search_query','search_location_id']).index.isin(tr.set_index(['search_query','search_location_id']).index).mean())
print('bench fullkey in train', bq.set_index(qkey).index.isin(tr.set_index(qkey).index).mean())
print('train items in bench corpus', tr.item_id.drop_duplicates().isin(set(bi.item_id)).mean())
print('bench corpus items seen in train', bi.item_id.isin(set(tr.item_id)).mean())
print('bench loc in train locs', bq.search_location_id.isin(set(tr.search_location_id)).mean())
print('same loc share train', (tr.search_location_id==tr.item_location_id).mean())
print('same cat share train', (tr.search_category==tr.item_category_id).mean())
print('search_category vc train\n', tr.search_category.value_counts().head(20))
print('search_category vc bench\n', bq.search_category.value_counts().head(20))
print('item_category vc corpus\n', bi.item_category_id.value_counts().head(20))
print('delivery share', tr.search_is_delivery_search.mean(), bq.search_is_delivery_search.mean())
print('infm empty share', (tr.search_infm_params_text.fillna('')=='').mean(), (bq.search_infm_params_text.fillna('')=='').mean())
print(bq.search_infm_params_text.value_counts().head(15))
print('n locations train', tr.search_location_id.nunique(), 'bench', bq.search_location_id.nunique(), 'corpus', bi.item_location_id.nunique())
print('microcats corpus', bi.item_microcat_id.nunique(), 'train', tr.item_microcat_id.nunique())
